-- =====================================================================
-- 001_schema.sql  -  Sterschema (schema dwh) voor SteelLine
-- =====================================================================
-- Uitvoeren als admin of etl_writer:
--   psql -h mordor -U admin -d steelline -f sql/001_schema.sql
--
-- Het schema dwh bestaat al (infra/initdb/01-roles.sh) en is eigendom
-- van etl_writer. We maken alles aan ALS etl_writer, zodat de
-- DEFAULT PRIVILEGES uit 01-roles.sh bi_reader automatisch SELECT geven.
--
-- Herhaalbaar: CREATE ... IF NOT EXISTS. Alles in één transactie:
-- faalt er iets, dan wordt niets half aangemaakt.
-- =====================================================================

\set ON_ERROR_STOP on
SET client_min_messages = warning;   -- geen "already exists"-meldingen bij herhalen

BEGIN;

SET ROLE etl_writer;
SET search_path = dwh;

-- ---------------------------------------------------------------------
-- DIMENSIES
-- ---------------------------------------------------------------------
-- Conventie:
--   *_key   = surrogaatsleutel (int, door de database gegenereerd)
--   *_code  = natuurlijke/bedrijfssleutel zoals de generator en de
--             webapp hem kennen ('WW1', 'S355J2', 'MECH-LAGER', ...).
--             De ETL zoekt hiermee de *_key op.
-- GENERATED BY DEFAULT (i.p.v. ALWAYS) zodat we een vaste
-- 'Onbekend'-rij met key -1 kunnen invoegen.
-- ---------------------------------------------------------------------

-- Kalender: 1 rij per dag. Sleutel = YYYYMMDD (bv. 20261112):
-- leesbaar, sorteerbaar en geen opzoeking nodig in de ETL.
CREATE TABLE IF NOT EXISTS dim_date (
    date_key        integer     PRIMARY KEY,           -- YYYYMMDD
    datum           date        NOT NULL UNIQUE,
    jaar            smallint    NOT NULL,
    kwartaal        smallint    NOT NULL CHECK (kwartaal BETWEEN 1 AND 4),
    maand           smallint    NOT NULL CHECK (maand BETWEEN 1 AND 12),
    maand_naam      text        NOT NULL,              -- 'november'
    iso_jaar        smallint    NOT NULL,              -- ISO-jaar hoort bij iso_week
    iso_week        smallint    NOT NULL CHECK (iso_week BETWEEN 1 AND 53),
    dag_van_week    smallint    NOT NULL CHECK (dag_van_week BETWEEN 1 AND 7), -- 1 = maandag
    dag_naam        text        NOT NULL,              -- 'donderdag'
    is_weekend      boolean     NOT NULL,
    is_feestdag     boolean     NOT NULL DEFAULT false,
    feestdag_naam   text,
    werkdag         boolean     NOT NULL,              -- geen weekend en geen feestdag
    CONSTRAINT ck_dim_date_key CHECK (date_key = to_char(datum, 'YYYYMMDD')::integer)
);

-- Ploeg. Productiedag-regel: de nachtploeg (22:00-06:00) hoort bij de
-- datum waarop hij BEGINT. Zie docs/datamodel.md.
CREATE TABLE IF NOT EXISTS dim_shift (
    shift_key       smallint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_code      text        NOT NULL UNIQUE,       -- 'VROEG', 'LAAT', 'NACHT'
    ploeg           text        NOT NULL,              -- 'vroeg', 'laat', 'nacht'
    start_tijd      time        NOT NULL,
    eind_tijd       time        NOT NULL,              -- nacht: eind < start
    ploegleider     text        NOT NULL               -- SCD type 1: overschreven bij wissel
);

CREATE TABLE IF NOT EXISTS dim_installation (
    installation_key      smallint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installation_code     text          NOT NULL UNIQUE,   -- 'WW1'
    naam                  text          NOT NULL,          -- 'Warmwals 1'
    soort                 text          NOT NULL,          -- warmwals, beitslijn, koudwals, gloeioven
    lijn                  text          NOT NULL,          -- 'Warmband', 'Koudband'
    volgorde_in_lijn      smallint      NOT NULL,          -- processtap 1, 2, 3 ...
    capaciteit_t_per_uur  numeric(7,1)  NOT NULL CHECK (capaciteit_t_per_uur > 0),
    actief                boolean       NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS dim_steel_grade (
    grade_key       smallint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade_code      text          NOT NULL UNIQUE,     -- 'S355J2'
    kwaliteit       text          NOT NULL,            -- omschrijving
    familie         text          NOT NULL,            -- constructiestaal, dieptrekstaal, ...
    min_dikte_mm    numeric(6,3)  NOT NULL CHECK (min_dikte_mm > 0),
    max_dikte_mm    numeric(6,3)  NOT NULL,
    CONSTRAINT ck_grade_dikte CHECK (max_dikte_mm > min_dikte_mm)
);

CREATE TABLE IF NOT EXISTS dim_downtime_reason (
    reason_key      smallint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reason_code     text        NOT NULL UNIQUE,       -- 'MECH-LAGER'
    categorie       text        NOT NULL CHECK (categorie IN
                        ('mechanisch', 'elektrisch', 'wissel', 'wachten op materiaal',
                         'gepland onderhoud', 'onbekend')),
    omschrijving    text        NOT NULL,
    standaard_gepland boolean   NOT NULL DEFAULT false -- bv. gepland onderhoud
);

-- ---------------------------------------------------------------------
-- FEITEN
-- ---------------------------------------------------------------------

-- 1 rij per geproduceerde rol (coil) per installatie.
-- coil_id is een 'degenerate dimension': geen eigen dimensietabel.
-- Een rol passeert meerdere installaties (warmwals -> beits -> koudwals),
-- daarom is (coil_id, installation_key) uniek, niet coil_id alleen.
CREATE TABLE IF NOT EXISTS fact_production (
    production_id         bigint        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    coil_id               text          NOT NULL,          -- 'C2026111200123'
    date_key              integer       NOT NULL REFERENCES dim_date (date_key),
    shift_key             smallint      NOT NULL REFERENCES dim_shift (shift_key),
    installation_key      smallint      NOT NULL REFERENCES dim_installation (installation_key),
    steel_grade_key       smallint      NOT NULL REFERENCES dim_steel_grade (grade_key),
    start_ts              timestamptz   NOT NULL,          -- begin bewerking
    weight_t              numeric(7,3)  NOT NULL CHECK (weight_t > 0 AND weight_t < 60),
    thickness_mm          numeric(6,3)  NOT NULL CHECK (thickness_mm > 0),
    target_thickness_mm   numeric(6,3)  NOT NULL CHECK (target_thickness_mm > 0),
    thickness_dev_mm      numeric(6,3)  GENERATED ALWAYS AS (thickness_mm - target_thickness_mm) STORED,
    temp_c                numeric(5,1)  CHECK (temp_c BETWEEN -20 AND 1400),  -- NULL mag (niet elke installatie meet)
    duration_min          numeric(7,2)  NOT NULL CHECK (duration_min > 0),
    is_defect             boolean       NOT NULL DEFAULT false,
    defect_type           text,                            -- 'oppervlaktefout', 'dikte buiten tolerantie', ...
    load_id               bigint        NOT NULL,          -- lineage: welke ETL-run (staging.load_batch)
    loaded_at             timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT uq_fact_production_coil UNIQUE (coil_id, installation_key),
    CONSTRAINT ck_defect_type CHECK (
        (is_defect AND defect_type IS NOT NULL) OR (NOT is_defect AND defect_type IS NULL))
);

-- 1 rij per stilstand. Komt van sensoren (generator) of van de
-- operator-webapp. source_event_id maakt laden herhaalbaar (upsert).
CREATE TABLE IF NOT EXISTS fact_downtime (
    downtime_id           bigint        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source                text          NOT NULL CHECK (source IN ('sensor', 'app')),
    source_event_id       text          NOT NULL,          -- id in het bronsysteem
    date_key              integer       NOT NULL REFERENCES dim_date (date_key),
    shift_key             smallint      NOT NULL REFERENCES dim_shift (shift_key),
    installation_key      smallint      NOT NULL REFERENCES dim_installation (installation_key),
    reason_key            smallint      NOT NULL DEFAULT -1 REFERENCES dim_downtime_reason (reason_key),
    start_ts              timestamptz   NOT NULL,
    end_ts                timestamptz,                     -- NULL = stilstand loopt nog (webapp)
    duration_min          numeric(8,2)  GENERATED ALWAYS AS
                              (round((extract(epoch FROM (end_ts - start_ts)) / 60)::numeric, 2)) STORED,
    planned               boolean       NOT NULL DEFAULT false,
    opmerking             text,
    load_id               bigint,                          -- NULL als de webapp rechtstreeks schrijft
    loaded_at             timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT uq_fact_downtime_source UNIQUE (source, source_event_id),
    CONSTRAINT ck_downtime_period CHECK (end_ts IS NULL OR end_ts > start_ts)
);

-- ---------------------------------------------------------------------
-- INDEXEN
-- ---------------------------------------------------------------------
-- PostgreSQL maakt automatisch indexen voor PRIMARY KEY en UNIQUE,
-- maar NIET voor vreemde sleutels. Die voegen we zelf toe: ze
-- versnellen joins/filters in Power BI en DELETE's op dimensies.
-- Volgorde: date_key eerst, want bijna elke query filtert op periode.

CREATE INDEX IF NOT EXISTS ix_fp_date_installation ON fact_production (date_key, installation_key);
CREATE INDEX IF NOT EXISTS ix_fp_shift             ON fact_production (shift_key);
CREATE INDEX IF NOT EXISTS ix_fp_installation      ON fact_production (installation_key);
CREATE INDEX IF NOT EXISTS ix_fp_steel_grade       ON fact_production (steel_grade_key);
CREATE INDEX IF NOT EXISTS ix_fp_defect            ON fact_production (date_key) WHERE is_defect;  -- partiële index: kwaliteitsrapport
CREATE INDEX IF NOT EXISTS ix_fp_load              ON fact_production (load_id);                   -- snel een foute run terugdraaien

CREATE INDEX IF NOT EXISTS ix_fd_date_installation ON fact_downtime (date_key, installation_key);
CREATE INDEX IF NOT EXISTS ix_fd_shift             ON fact_downtime (shift_key);
CREATE INDEX IF NOT EXISTS ix_fd_installation      ON fact_downtime (installation_key);
CREATE INDEX IF NOT EXISTS ix_fd_reason            ON fact_downtime (reason_key);
CREATE INDEX IF NOT EXISTS ix_fd_start_ts          ON fact_downtime (start_ts);
CREATE INDEX IF NOT EXISTS ix_fd_open              ON fact_downtime (installation_key) WHERE end_ts IS NULL; -- lopende stilstanden (webapp)
CREATE INDEX IF NOT EXISTS ix_fd_load              ON fact_downtime (load_id);

-- ---------------------------------------------------------------------
-- DOCUMENTATIE IN DE DATABASE (zichtbaar in DBeaver en voor de AI-laag)
-- ---------------------------------------------------------------------
COMMENT ON TABLE  dim_date            IS 'Kalenderdimensie, 1 rij per dag. date_key = YYYYMMDD.';
COMMENT ON TABLE  dim_shift           IS 'Ploegen. Nachtploeg hoort bij de datum waarop hij begint.';
COMMENT ON TABLE  dim_installation    IS 'Installaties van de fabriek (warmwals, beitslijn, koudwals, gloeioven).';
COMMENT ON TABLE  dim_steel_grade     IS 'Staalkwaliteiten met toegelaten diktebereik.';
COMMENT ON TABLE  dim_downtime_reason IS 'Oorzaken van stilstand. reason_key -1 = onbekend.';
COMMENT ON TABLE  fact_production     IS 'Feit: 1 rij per rol (coil) per installatie.';
COMMENT ON TABLE  fact_downtime       IS 'Feit: 1 rij per stilstand (sensor of operator-app).';
COMMENT ON COLUMN fact_production.coil_id          IS 'Rolnummer (degenerate dimension).';
COMMENT ON COLUMN fact_production.thickness_dev_mm IS 'Afwijking gemeten - doel (mm), berekend.';
COMMENT ON COLUMN fact_production.load_id          IS 'ETL-run die deze rij laadde (staging.load_batch).';
COMMENT ON COLUMN fact_downtime.end_ts             IS 'NULL zolang de stilstand nog loopt.';
COMMENT ON COLUMN fact_downtime.duration_min       IS 'Berekend uit end_ts - start_ts (minuten).';

RESET ROLE;
COMMIT;
